"""Multi-turn rollout with search-engine calls (Search-R1, Algorithm 1).

Each trajectory keeps its response as a flat token list plus a parallel mask:
    resp_mask[t] = 1  -> token generated by the policy (trained on)
    resp_mask[t] = 0  -> token inserted by the environment (<information> blocks,
                         invalid-action messages) -> excluded from every loss
                         ("retrieved token loss masking").
This module does not import torch, so it can be unit-tested on CPU.
"""
import re
from dataclasses import dataclass, field

STOP = ["</search>", "</answer>"]
_ACTION_RE = re.compile(r"<(search|answer)>(.*?)</\1>", re.DOTALL)
INVALID_MSG = (
    "\nMy previous action is invalid. If I want to search, I should put the query between "
    "<search> and </search>. If I want to give the final answer, I should put the answer "
    "between <answer> and </answer>. Let me try again.\n"
)


@dataclass
class RolloutConfig:
    max_turns: int = 4                  # number of search actions allowed; one extra final turn to answer
    max_tokens_per_turn: int = 500
    max_obs_tokens: int = 500
    max_response_tokens: int = 3000     # hard cap on the whole response (model + retrieved)
    temperature: float = 1.0


@dataclass
class Trajectory:
    prompt_ids: list
    resp_ids: list = field(default_factory=list)
    resp_mask: list = field(default_factory=list)
    model_text: list = field(default_factory=list)
    full_text: list = field(default_factory=list)
    n_search: int = 0
    n_invalid: int = 0
    answer: str | None = None
    done: bool = False

    def add(self, ids, text, is_model: bool):
        self.resp_ids += ids
        self.resp_mask += [1 if is_model else 0] * len(ids)
        self.full_text.append(text)
        if is_model:
            self.model_text.append(text)

    @property
    def response_text(self) -> str:
        return "".join(self.full_text)


def truncate_at_stop(text: str, stops=STOP) -> str:
    """Cut generated text right after the first stop string (keeps the stop string)."""
    cut = None
    for s in stops:
        i = text.find(s)
        if i != -1 and (cut is None or i + len(s) < cut):
            cut = i + len(s)
    return text if cut is None else text[:cut]


def parse_action(text: str):
    m = _ACTION_RE.search(text)
    if m is None:
        return None, None
    return m.group(1), m.group(2).strip()


def run_rollouts(prompt_ids_list, generator, retriever, tokenizer, cfg: RolloutConfig):
    trajs = [Trajectory(list(p)) for p in prompt_ids_list]
    for turn in range(cfg.max_turns + 1):
        active = [t for t in trajs if not t.done]
        if not active:
            break
        final_turn = turn == cfg.max_turns
        texts = generator.generate(
            [t.prompt_ids + t.resp_ids for t in active],
            max_new_tokens=cfg.max_tokens_per_turn,
            temperature=cfg.temperature,
            stop=STOP,
        )
        search_trajs, queries = [], []
        for t, text in zip(active, texts):
            text = truncate_at_stop(text)
            t.add(tokenizer.encode(text, add_special_tokens=False), text, is_model=True)
            action, content = parse_action(text)
            if action == "answer":
                t.answer, t.done = content, True
            elif final_turn:
                t.done = True                        # out of budget; no answer -> reward 0
            elif action == "search" and content:
                search_trajs.append(t)
                queries.append(content)
            else:
                t.add(tokenizer.encode(INVALID_MSG, add_special_tokens=False), INVALID_MSG, is_model=False)
                t.n_invalid += 1
        if queries:
            for t, docs in zip(search_trajs, retriever.search(queries)):
                obs_ids = tokenizer.encode(docs.strip(), add_special_tokens=False)[: cfg.max_obs_tokens]
                obs = "\n\n<information>" + tokenizer.decode(obs_ids) + "</information>\n\n"
                t.add(tokenizer.encode(obs, add_special_tokens=False), obs, is_model=False)
                t.n_search += 1
        for t in active:
            if len(t.resp_ids) >= cfg.max_response_tokens:
                t.resp_ids = t.resp_ids[: cfg.max_response_tokens]
                t.resp_mask = t.resp_mask[: cfg.max_response_tokens]
                t.done = True
    return trajs
